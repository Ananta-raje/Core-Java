package com.operators;

public class RelationalOperators {
	public static void main(String[] args) {
		int reqAge = 18;
		int currAge = 22;
		
		System.out.println(reqAge == currAge);
		System.out.println(reqAge != currAge);
		System.out.println(reqAge > currAge);
		System.out.println(reqAge < currAge);
		System.out.println(reqAge >= currAge);
		System.out.println(reqAge <= currAge);
		
	}
}
