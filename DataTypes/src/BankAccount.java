
public class BankAccount {

    public static void main(String[] args) {

        byte accountType = 1;
        short accountAge = 5;
        int accountNo = 10025;
        long accountNumber = 123456789012L;
        float interestRate = 6.5f;
        double balance = 75000.75;
        char accountGrade = 'A';
        boolean isActive = true;

        System.out.println("Account Type: " + accountType);
        System.out.println("Account Age: " + accountAge);
        System.out.println("Account No: " + accountNo);
        System.out.println("Account Number: " + accountNumber);
        System.out.println("Interest Rate: " + interestRate);
        System.out.println("Balance: " + balance);
        System.out.println("Account Grade: " + accountGrade);
        System.out.println("Account Active: " + isActive);
    }
}
